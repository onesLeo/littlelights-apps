// Writes supabase/seed/20261027_smallest_star_story.sql: "The Smallest Star" (Goodnight Little Light #1) as a
// draft Studio post (type 'story'). Fields come word for word from supabase/seed/smallest-star-fields.json
// (Taman's Studio fields). Nothing is written to the database from here; Taman applies the SQL file.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const STAR_SLUG = 'the-smallest-star';
export const STAR_AUDIO = 'https://media.littlesaltandlight.com/audio/the-smallest-star.6b731d78.mp3';
export async function starFields() { return JSON.parse(await readFile(resolve(root, 'supabase/seed/smallest-star-fields.json'), 'utf8')); }

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
export async function seedSql() {
  const f = await starFields();
  return `-- The Smallest Star (Goodnight Little Light #1) as a DRAFT Studio post (no publish date yet).
-- Generated by scripts/seed-smallest-star.mjs from supabase/seed/smallest-star-fields.json (word for word).
-- Apply AFTER supabase/migrations/20261027120000_bedtime_story_posts.sql, in the SQL Editor.
-- Safe to run twice: an existing post with this slug is left alone.
-- Audio: audio/the-smallest-star.6b731d78.mp3 on R2 (8,573,229 bytes, 357.19 s).
-- Timings: media/audio/the-smallest-star-timings.json (in the repo, precached by sw.js).
-- To publish: open it in the Studio, pick a publish date, and Schedule.
insert into public.posts (type, status, publish_at, title, slug, show_on_today, fields, media_url, author_email)
values ('story', 'draft', null, ${q('The Smallest Star')}, ${q(STAR_SLUG)}, false,
  ${q(JSON.stringify(f, null, 2))}::jsonb,
  ${q(STAR_AUDIO)},
  null)
on conflict (slug) do nothing;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(resolve(root, 'supabase/seed/20261027_smallest_star_story.sql'), await seedSql());
  console.log('wrote supabase/seed/20261027_smallest_star_story.sql');
}
