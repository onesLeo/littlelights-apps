// Writes supabase/seed/20261027_elijah_story.sql: the Elijah bedtime story from js/content.js as a Studio
// post (type 'story') scheduled for Mon 9 Nov 2026, 00:00 Singapore time. Text is copied from js/content.js
// word for word (run again after any change there). Taman applies the file in the SQL Editor; nothing is
// written to the database from here.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
export const ELIJAH_SLUG = 'elijah-still-small-voice-bedtime-story';
export const ELIJAH_PUBLISH_AT = '2026-11-09T00:00:00+08:00';

// The story as it was in js/content.js (until it became Studio-only): supabase/seed/elijah-story.json.
export async function builtinStory(slug) {
  if (slug === ELIJAH_SLUG) return JSON.parse(await readFile(resolve(root, 'supabase/seed/elijah-story.json'), 'utf8'));
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(await readFile(resolve(root, 'js/content.js'), 'utf8'), ctx);
  return JSON.parse(JSON.stringify(ctx.window.LL_CONTENT.bedtimeStories.find((x) => x.slug === slug)));
}

// The Studio's `fields` for a built-in story (inverse of storyFromPost in js/store.js).
export function fieldsFromStory(x) {
  const f = {
    series: x.series, episode: x.episode, narrator: x.narrator, desc: x.desc, seo_title: x.seoTitle,
    seconds: x.dur, minutes: Math.floor(x.dur / 60) + ':' + String(Math.round(x.dur % 60)).padStart(2, '0'),
    story: x.story.join('\n\n'), prayer: x.prayer, goodnight: x.goodnight,
    verse: x.verse.text, ref: x.verse.ref, translation: x.verse.version, questions: x.questions.join('\n'),
    timings: x.timings, color: x.color, ink: x.ink, publish_date: ELIJAH_PUBLISH_AT.slice(0, 10),
    builtin: 'story:' + x.slug,
  };
  if (x.word) { f.word = x.word.word; f.word_meaning = x.word.meaning; }
  if (x.image) { f.image = x.image; f.image_width = x.imageWidth; f.image_height = x.imageHeight; }
  if (x.next) { f.next_title = x.next.title; f.next_when = x.next.when; f.next_href = x.next.href; }
  return f;
}

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
export async function seedSql() {
  const x = await builtinStory(ELIJAH_SLUG);
  const f = fieldsFromStory(x);
  return `-- Elijah and the Still Small Voice (Bedtime Bible Story #2) as a Studio post, scheduled for
-- Mon 9 Nov 2026 00:00 SGT. Generated by scripts/seed-elijah.mjs from js/content.js (word for word).
-- Apply AFTER supabase/migrations/20261027120000_bedtime_story_posts.sql, in the SQL Editor.
-- Safe to run twice: an existing post with this slug is left alone.
-- Audio: audio/elijah-still-small-voice.0d7d251e.mp3 on R2 (uploaded by Taman, 27 Oct 2026).
insert into public.posts (type, status, publish_at, title, slug, show_on_today, fields, media_url, author_email)
values ('story', 'scheduled', ${q(ELIJAH_PUBLISH_AT)}, ${q(x.title)}, ${q(x.slug)}, false,
  ${q(JSON.stringify(f, null, 2))}::jsonb,
  ${q(x.src)},
  null)
on conflict (slug) do nothing;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await mkdir(resolve(root, 'supabase/seed'), { recursive: true });
  await writeFile(resolve(root, 'supabase/seed/20261027_elijah_story.sql'), await seedSql());
  console.log('wrote supabase/seed/20261027_elijah_story.sql');
}
